"""
clean_data.py
Phase 2 (Data Preprocessing & Cleaning):
Clean labeled maze dataset generated by compute_labels.py.

Operations performed:
1. Unreachable Paths & Cells:
   - Identify and drop entire mazes where the start-to-goal path is unreachable (opt_cost == inf).
   - Identify cells where h*(n) = inf (wall cells or unreachable free cells) and set them to -1.0
     as a clean numerical sentinel value for downstream models.
2. Deduplication:
   - Compute MD5 hashes of grid topologies to identify and filter out duplicate maze structures.
3. Outlier Filtering:
   - Calculate Interquartile Range (IQR) on optimal path costs (opt_cost) grouped per grid size
     to flag and drop extreme path cost outliers.
4. Logging & Output:
   - Output clean compressed npz files to data/cleaned/.
   - Record comprehensive statistics and parameters to data_scripts/clean_log.json.
   - Display a formatted summary table of cleaning metrics.

Usage:
  python data_scripts/clean_data.py
  python data_scripts/clean_data.py --labeled data/labeled --out data/cleaned --log data_scripts/clean_log.json
"""

import argparse
import glob
import hashlib
import json
import os
import numpy as np


def compute_grid_hash(grid: np.ndarray) -> str:
    """Compute MD5 hash of grid topology for deduplication."""
    return hashlib.md5(grid.tobytes()).hexdigest()


def calculate_iqr_bounds(costs: np.ndarray, factor: float = 1.5):
    """Calculate IQR bounds (lower_bound, upper_bound) for an array of path costs."""
    if len(costs) == 0:
        return -np.inf, np.inf, 0.0, 0.0, 0.0
    q1 = float(np.percentile(costs, 25))
    q3 = float(np.percentile(costs, 75))
    iqr = q3 - q1
    lower_bound = q1 - factor * iqr
    upper_bound = q3 + factor * iqr
    return lower_bound, upper_bound, q1, q3, iqr


def main():
    parser = argparse.ArgumentParser(description="Data Cleaning for Neural Heuristic Search")
    parser.add_argument("--labeled", default="data/labeled", help="Input directory containing labeled npz files")
    parser.add_argument("--out", default="data/cleaned", help="Output directory for cleaned npz files")
    parser.add_argument("--log", default="data_scripts/clean_log.json", help="Path for JSON metrics log")
    parser.add_argument("--iqr-factor", type=float, default=1.5, help="IQR factor for outlier thresholding (default: 1.5)")
    args = parser.parse_args()

    files = sorted(glob.glob(os.path.join(args.labeled, "*.npz")))
    if not files:
        raise SystemExit(f"Error: No .npz files found in '{args.labeled}'. Run compute_labels.py first.")

    os.makedirs(args.out, exist_ok=True)
    os.makedirs(os.path.dirname(args.log), exist_ok=True)

    # -------------------------------------------------------------------------
    # PASS 1: Index all mazes, perform deduplication, and collect opt_costs per grid size
    # -------------------------------------------------------------------------
    seen_grid_hashes = set()
    file_maze_records = []  # Metadata records per maze across files

    # Track overall counters
    initial_total_mazes = 0
    dropped_unreachable_count = 0
    dropped_duplicate_count = 0

    # Map grid size -> list of (opt_cost, maze_id) for IQR outlier detection
    costs_by_size = {}

    global_maze_id = 0

    for file_path in files:
        file_name = os.path.basename(file_path)
        data = np.load(file_path)
        grids = data["grids"]
        starts = data["starts"]
        goals = data["goals"]
        h_star = data["h_star"]
        opt_cost = data["opt_cost"]

        num_mazes = len(grids)
        initial_total_mazes += num_mazes

        file_records = []

        for i in range(num_mazes):
            g = grids[i]
            cost = float(opt_cost[i])
            size = int(g.shape[0])

            is_unreachable = not np.isfinite(cost)
            g_hash = compute_grid_hash(g)
            is_duplicate = False

            if is_unreachable:
                dropped_unreachable_count += 1
            else:
                if g_hash in seen_grid_hashes:
                    is_duplicate = True
                    dropped_duplicate_count += 1
                else:
                    seen_grid_hashes.add(g_hash)

                    if size not in costs_by_size:
                        costs_by_size[size] = []
                    costs_by_size[size].append((cost, global_maze_id))

            record = {
                "global_id": global_maze_id,
                "local_idx": i,
                "file_name": file_name,
                "size": size,
                "cost": cost,
                "is_unreachable": is_unreachable,
                "is_duplicate": is_duplicate,
                "is_outlier": False,  # Evaluated in Pass 2
            }
            file_records.append(record)
            global_maze_id += 1

        file_maze_records.append((file_path, file_records))

    # -------------------------------------------------------------------------
    # Compute IQR bounds per grid size and flag outliers
    # -------------------------------------------------------------------------
    iqr_bounds_info = {}
    outlier_global_ids = set()
    dropped_outlier_count = 0

    for size, items in costs_by_size.items():
        costs_arr = np.array([item[0] for item in items], dtype=np.float32)
        lower_b, upper_b, q1, q3, iqr = calculate_iqr_bounds(costs_arr, factor=args.iqr_factor)

        iqr_bounds_info[str(size)] = {
            "sample_count": len(costs_arr),
            "q1": q1,
            "q3": q3,
            "iqr": iqr,
            "lower_bound": lower_b,
            "upper_bound": upper_b,
        }

        # Flag outliers
        for cost, gid in items:
            if cost < lower_b or cost > upper_b:
                outlier_global_ids.add(gid)
                dropped_outlier_count += 1

    # Update outlier flags in file_records
    for file_path, records in file_maze_records:
        for rec in records:
            if rec["global_id"] in outlier_global_ids:
                rec["is_outlier"] = True

    # -------------------------------------------------------------------------
    # PASS 2: Filter datasets, sanitize unreachable cells in h_star, and write output
    # -------------------------------------------------------------------------
    file_log_entries = []
    final_total_mazes = 0
    total_cells_inspected = 0
    total_unreachable_cells = 0

    for file_path, records in file_maze_records:
        file_name = os.path.basename(file_path)
        data = np.load(file_path)
        grids = data["grids"]
        starts = data["starts"]
        goals = data["goals"]
        h_star = data["h_star"]
        opt_cost = data["opt_cost"]

        # Indices to keep
        keep_indices = []
        file_unreachable_cells = 0

        for rec in records:
            if not rec["is_unreachable"] and not rec["is_duplicate"] and not rec["is_outlier"]:
                keep_indices.append(rec["local_idx"])

        if keep_indices:
            clean_grids = grids[keep_indices]
            clean_starts = starts[keep_indices]
            clean_goals = goals[keep_indices]
            clean_h_star = h_star[keep_indices].copy()
            clean_opt_cost = opt_cost[keep_indices]

            # Replace infinite h*(n) cells with -1.0 sentinel (wall / unreachable cell)
            unreachable_mask = ~np.isfinite(clean_h_star)
            file_unreachable_cells = int(np.sum(unreachable_mask))
            clean_h_star[unreachable_mask] = -1.0

            total_cells_inspected += int(clean_h_star.size)
            total_unreachable_cells += file_unreachable_cells

            out_path = os.path.join(args.out, file_name)
            np.savez_compressed(
                out_path,
                grids=clean_grids,
                starts=clean_starts,
                goals=clean_goals,
                h_star=clean_h_star,
                opt_cost=clean_opt_cost,
            )
            cleaned_count = len(clean_grids)
        else:
            cleaned_count = 0

        final_total_mazes += cleaned_count

        dropped_unreachable_file = sum(1 for r in records if r["is_unreachable"])
        dropped_dup_file = sum(1 for r in records if not r["is_unreachable"] and r["is_duplicate"])
        dropped_outlier_file = sum(1 for r in records if not r["is_unreachable"] and not r["is_duplicate"] and r["is_outlier"])

        file_log_entries.append({
            "file": file_name,
            "initial_mazes": len(records),
            "dropped_unreachable_mazes": dropped_unreachable_file,
            "dropped_duplicate_mazes": dropped_dup_file,
            "dropped_outlier_mazes": dropped_outlier_file,
            "cleaned_mazes": cleaned_count,
            "unreachable_cells_set_sentinel": file_unreachable_cells,
        })

    # -------------------------------------------------------------------------
    # Construct Summary & Save Log JSON
    # -------------------------------------------------------------------------
    log_data = {
        "summary": {
            "initial_total_mazes": initial_total_mazes,
            "dropped_unreachable_mazes": dropped_unreachable_count,
            "dropped_duplicate_mazes": dropped_duplicate_count,
            "dropped_outlier_mazes": dropped_outlier_count,
            "final_cleaned_mazes": final_total_mazes,
            "total_cells_inspected": total_cells_inspected,
            "total_unreachable_cells_set_sentinel": total_unreachable_cells,
        },
        "iqr_bounds_per_size": iqr_bounds_info,
        "files": file_log_entries,
    }

    with open(args.log, "w") as f:
        json.dump(log_data, f, indent=2)

    # -------------------------------------------------------------------------
    # Print Clean Summary Table
    # -------------------------------------------------------------------------
    pct = lambda count, total: (count / total * 100) if total > 0 else 0.0

    print("\n" + "=" * 70)
    print(" " * 18 + "DATA CLEANING SUMMARY TABLE")
    print("=" * 70)
    print(f"{'Metric':<42} | {'Count':<10} | {'Percentage':<10}")
    print("-" * 70)
    print(f"{'Initial Total Mazes':<42} | {initial_total_mazes:<10} | {100.00:6.2f}%")
    print(f"{'Dropped Unreachable Mazes (opt_cost=inf)':<42} | {dropped_unreachable_count:<10} | {pct(dropped_unreachable_count, initial_total_mazes):6.2f}%")
    print(f"{'Dropped Duplicate Mazes (MD5 topologies)':<42} | {dropped_duplicate_count:<10} | {pct(dropped_duplicate_count, initial_total_mazes):6.2f}%")
    print(f"{'Dropped Outlier Mazes (IQR filtered)':<42} | {dropped_outlier_count:<10} | {pct(dropped_outlier_count, initial_total_mazes):6.2f}%")
    print("-" * 70)
    print(f"{'Final Cleaned Mazes':<42} | {final_total_mazes:<10} | {pct(final_total_mazes, initial_total_mazes):6.2f}%")
    print("-" * 70)
    print(f"{'Total Cells Inspected':<42} | {total_cells_inspected:<10} | {100.00:6.2f}%")
    print(f"{'Unreachable Cells Set to Sentinel (-1.0)':<42} | {total_unreachable_cells:<10} | {pct(total_unreachable_cells, total_cells_inspected):6.2f}%")
    print("=" * 70)
    print(f"Cleaned datasets saved to: {args.out}")
    print(f"Metrics log written to:    {args.log}\n")


if __name__ == "__main__":
    main()
